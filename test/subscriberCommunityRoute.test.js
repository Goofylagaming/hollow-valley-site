const test = require("node:test");
const assert = require("node:assert/strict");
process.env.DB_PATH = ":memory:";
process.env.SUBSCRIBER_COMMUNITY_ENABLED = "1";
process.env.MEMBERSHIP_REWARDS_ENABLED = "1";
const express = require("express");
const { db } = require("../server/db");
require("../server/services/supporterWebhook");
const community = require("../server/services/subscriberCommunity");
test("community HTTP authentication, admin authorization, same-origin enforcement and safe dry-run", async t => {
  community.schema();
  db.prepare("INSERT INTO users(id,username,is_admin) VALUES (1,'Member',0),(2,'Admin',1)").run();
  db.prepare("INSERT INTO supporter_subscriptions(user_id,tier,stripe_status,renews_at) VALUES (1,'supporter','active',?)").run(new Date(Date.now()+86400000).toISOString());
  const app = express(); app.use(express.json()); app.use((req, res, next) => { req.user = req.get("x-user") === "admin" ? {id:2,is_admin:1} : req.get("x-user") === "member" ? {id:1} : null; next(); });
  app.use("/api/subscriber-community", require("../server/routes/subscriberCommunity"));
  const server = app.listen(0, "127.0.0.1"); await new Promise(resolve => server.once("listening", resolve)); t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (path, user, body, origin=base) => fetch(base+"/api/subscriber-community"+path, {method:body ? "POST" : "GET", headers:{"Content-Type":"application/json", "x-user":user||"", origin}, ...(body ? {body:JSON.stringify(body)} : {})});
  assert.equal((await call("/admin")).status, 401);
  assert.equal((await call("/admin", "member")).status, 403);
  assert.equal((await call("/suggestions", "member", {text:"Forest event"}, "https://attacker.test")).status, 403);
  assert.equal((await call("/suggestions", "member", {text:"Forest event"})).status, 200);
  const preview = await call("/admin/posts", "admin", {kind:"dev-preview",text:"A new forest preview"});
  assert.equal(preview.status,200); assert.equal((await preview.json()).dryRun,true);
  assert.equal(db.prepare("SELECT COUNT(*) n FROM subscriber_community_posts").get().n,0);
  const delivery = await call("/admin/deliver", "admin", {}); assert.equal((await delivery.json()).dryRun,true);
  process.env.SUBSCRIBER_COMMUNITY_ENABLED="0";
  assert.equal((await call("/admin", "admin")).status,503);
});
