const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const express=require('express');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'hv-achievement-review-'));
process.env.AUTOMATION_DB_PATH=path.join(dir,'test.sqlite');
process.env.AUTOMATION_ADMIN_TOKEN='fixture-admin-token';
const store=require('../src/services/economyStore');
const progression=require('../src/services/progressionService');
const review=require('../src/services/achievementEvidenceReview').createAchievementEvidenceReview(store.db);
const steamId='76561198000000691',actorSteamId='76561198000000692';
const achievementId='life-survival-10h';
test.after(()=>{store.db.close();fs.rmSync(dir,{recursive:true,force:true});});

test('authenticated review preserves awards, supports restoration and rejects conflicting decisions',async()=>{
  progression.getProfile(steamId);
  store.db.prepare('INSERT INTO progression_achievements(steam_id,achievement_id,metadata_json) VALUES (?,?,?)').run(steamId,achievementId,'{}');
  store.db.prepare('INSERT INTO progression_achievement_evidence_reviews VALUES (?,?,?,?,?,?)').run(steamId,achievementId,'combat-death','fixture-death',1,'pending');
  const original=store.db.prepare('SELECT * FROM progression_achievements WHERE steam_id=?').all(steamId);
  const before=progression.getProfile(steamId).achievementCount;
  const app=express();app.use(express.json());app.use('/review',require('../src/routes/achievementReviewRoutes'));
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  const url=`http://127.0.0.1:${server.address().port}/review`;
  const headers={Authorization:'Bearer fixture-admin-token','Content-Type':'application/json'};
  const payload={requestId:'decision-001',steamId,achievementId,actorSteamId,decision:'withdraw',reason:'Death occurred before ten observed hours',expectedRevision:0};
  const post=(body,auth=headers)=>fetch(url,{method:'POST',headers:auth,body:JSON.stringify(body)});
  try {
    assert.equal((await fetch(url)).status,401);
    assert.equal((await post(payload,{'Content-Type':'application/json',Authorization:'Bearer website-only'})).status,401);
    assert.equal((await post({...payload,reason:'short'})).status,400);
    assert.equal((await post(payload)).status,200);
    assert.equal(progression.getProfile(steamId).achievementCount,before-1);
    assert.equal(progression.getProfile(steamId).achievements.find(a=>a.id===achievementId).verificationStatus,'withdrawn');
    assert.deepEqual(await (await post(payload)).json(),{duplicate:true,revision:1});
    assert.equal((await post({...payload,decision:'uphold'})).status,409);
    assert.equal((await post({...payload,requestId:'decision-002'})).status,409);
    assert.equal((await post({...payload,requestId:'decision-003',expectedRevision:1,decision:'uphold',reason:'Corrected server evidence confirms survival'})).status,200);
    assert.equal(progression.getProfile(steamId).achievementCount,before);
    assert.equal(progression.getProfile(steamId).achievements.find(a=>a.id===achievementId).verificationStatus,undefined);
    const response=await fetch(url,{headers});assert.equal(response.headers.get('cache-control'),'no-store');
    const row=(await response.json()).reviews[0];
    assert.equal(row.revision,2);assert.equal(row.pendingCount,0);assert.equal(row.decisions.length,2);
    assert.equal(row.decisions[0].actorSteamId,actorSteamId);
    assert.deepEqual(store.db.prepare('SELECT * FROM progression_achievements WHERE steam_id=?').all(steamId),original);
    assert.equal(store.getWallet(steamId).balance,0);
    assert.equal(progression.getProfile(steamId).xp,0);
    store.db.exec('CREATE TABLE vl_lives(id TEXT PRIMARY KEY,steam_id TEXT,started_at INTEGER,ended_at INTEGER)');
    store.db.prepare('INSERT INTO vl_lives VALUES (?,?,0,NULL)').run('life-fixture',steamId);
    store.db.prepare('UPDATE progression_achievements SET metadata_json=? WHERE steam_id=? AND achievement_id=?').run(JSON.stringify({evidence:{lifeId:'life-fixture',observedThrough:10000}}),steamId,achievementId);
    store.db.exec('CREATE TABLE combat_events(id TEXT,victim_steam_id TEXT,occurred_at TEXT)');
    store.db.prepare('INSERT INTO combat_events VALUES (?,?,?)').run('new-death',steamId,new Date(5000).toISOString());
    assert.equal(review.inspect(steamId).has(achievementId),true);
    assert.equal(review.list()[0].revision,3);
    review.inspect(steamId);assert.equal(review.list()[0].revision,3,'repeat detection does not change revision');
    assert.equal((await post({...payload,requestId:'decision-004',expectedRevision:2})).status,409,'new evidence invalidates an old admin view');
    store.db.prepare('INSERT INTO combat_events VALUES (?,?,?)').run('newer-death',steamId,new Date(6000).toISOString());
    assert.equal((await post({...payload,requestId:'decision-005',expectedRevision:3})).status,409,'decision checks fresh evidence without a profile visit');
    assert.equal(review.list()[0].revision,4);
    assert.equal(review.list()[0].evidence.find(e=>e.id==='newer-death').occurredAt,new Date(6000).toISOString());
    assert.throws(()=>review.decide(null),{status:400});
  } finally {await new Promise(resolve=>server.close(resolve));}
});
